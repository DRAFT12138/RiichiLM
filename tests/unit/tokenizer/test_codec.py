@pytest.mark.parametrize('kind,args,expected', ACTIONS)
def test_all_actions(codec, kind, args, expected):
    action = Action(kind, tuple(Atom(v) if type(v) is str else v for v in args))
    encoded = ids(codec, expected)
    assert codec.encode_action_suffix(action) == encoded
    decoded = codec.decode_action_suffix(encoded)
    assert codec.encode_action_suffix(decoded) == encoded
    archive = [31, *encoded[:-1], 32]
    assert codec.encode_action(action) == archive
    assert codec.decode_action(archive) == decoded
    with pytest.raises(ProtocolError):
        codec.decode_action_suffix(archive)
    with pytest.raises(ProtocolError):
        codec.decode_action(encoded)
    with pytest.raises(ProtocolError):
        codec.decode_action_suffix(encoded[:-1])
    with pytest.raises(ProtocolError):
        codec.decode_action_suffix(encoded[:-1] + [512, 30])


def test_action_business_values_pass_through(codec):
    # Deliberately invalid game requests remain representable: preprocessing owns checks.
    for action in [Action('A_KAKAN', (-1, Atom('TILE_1m'))),
                   Action('A_DISCARD', (Atom('TILE_HIDDEN'), Atom('UNKNOWN'))),
                   Action('A_RON', (Atom('ABS_P0'), Atom('TILE_1m')))]:
        assert codec.decode_action_suffix(codec.encode_action_suffix(action)) == action


def test_unsorted_consumed_parses_without_validation(codec):
    raw = ids(codec, 'A_CHI KAMICHA TILE_4m TILE_6m TILE_5mr END_DECISION')
    action = codec.decode_action_suffix(raw)
    assert action.args[2:] == (Atom('TILE_6m'), Atom('TILE_5mr'))
    assert codec.encode_action_suffix(action) == ids(codec, 'A_CHI KAMICHA TILE_4m TILE_5mr TILE_6m END_DECISION')


def test_header_independent_id_vector(codec):
    # F_SCORES=365 precedes F_SEAT_WINDS=366, even though prose lists winds first.
    expected = [23,4,358,98,360,101,361,513,362,512,363,512,364,86,365,6]
    expected += [8,10,514,517,512,512,512,9] * 4
    expected += [7,366,6,75,76,77,78,7,5,24]
    assert codec.encode_header(header()) == expected
    assert codec.encode_header(dict(reversed(list(header().items())))) == expected
    assert codec.decode_header(expected) == header()


@pytest.mark.parametrize('key,value', [
    ('round_number', True), ('round_number', 0), ('round_number', 5),
    ('honba', -1), ('kyotaku', Atom('UNKNOWN')),
    ('dealer', Atom('ABS_P0')), ('mode', 'MODE_HANCHAN'),
    ('round_wind', None), ('scores', [True, 0, 0, 0]),
    ('seat_winds', [Atom('TILE_E')] * 4),
    ('profile_index', 0), ('rule_options', {}), ('hands', []),
])
def test_header_business_fields_are_not_validated(codec, key, value):
    obj = header()
    obj[key] = value
    assert codec.decode_header(codec.encode_header(obj)) == obj


@pytest.mark.parametrize('key', list(header()))
def test_header_missing_fields_are_preprocessing_responsibility(codec, key):
    obj = header()
    del obj[key]
    assert codec.decode_header(codec.encode_header(obj)) == obj


def test_packaged_vocabulary_and_old_binding(codec):
    root = Path(__file__).resolve().parents[3]
    resource = root / 'src/mahjong/tokenizer/resources'
    current = json.loads((resource / 'vocab-v2.manifest.json').read_text())
    codec.validate_binding(current)
    for field, value in [('name', 'majang-4p-v1'), ('ir_schema_version', 'majang-ir/1'),
                         ('sequence_schema_version', 'majang-sequence/1.1'),
                         ('task', 'policy-current-private/1'), ('vocab_sha256', '0' * 64)]:
        with pytest.raises(ProtocolError):
            codec.validate_binding({**current, field: value})
    assert [codec.token_id(x) for x in ('HAND_STATE', 'HAND_MELDS_SEP', 'END_HAND_STATE')] == [640,641,642]
