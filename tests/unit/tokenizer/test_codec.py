from decimal import Decimal, localcontext
import json
from pathlib import Path

import pytest

from mahjong.tokenizer import Action, Atom, Extension, MahjongTokenizer, ProtocolError


@pytest.fixture
def codec():
    return MahjongTokenizer()


def ids(codec, text):
    return [codec.token_id(x) for x in text.split()]


def header():
    return dict(mode=Atom('MODE_HANCHAN'), round_wind=Atom('ROUND_E'),
                round_number=1, honba=0, kyotaku=0, dealer=Atom('SELF'),
                scores=[25000] * 4, seat_winds=[Atom('TILE_' + x) for x in 'ESWN'])


@pytest.mark.parametrize('value,expected', [
    (0, [512]), (127, [639]), (128, [8,10,513,514,520,9]),
    (-800, [8,11,520,512,512,9]),
    (25000, [8,10,514,517,512,512,512,9]),
    (Decimal('12.500'), [16,637,513]), (Decimal('-0.00'), [16,512,512]),
    (None, [17]), (True, [45]), (False, [46]),
    (Atom('UNKNOWN'), [18]), (Atom('HIDDEN'), [19]),
    ('<EOS>', [12,828,837,847,851,830,13]),
    (b'\x00\xff', [14,768,1023,15]),
    ([], [6,7]), ({}, [4,5]),
])
def test_independent_base_vectors(codec, value, expected):
    assert codec.encode_value(value) == expected
    assert codec.decode_value(expected) == value


def test_exact_decimal_is_independent_of_python_context(codec):
    value = Decimal('123456789012345678901234567890.123456789')
    with localcontext() as ctx:
        ctx.prec = 3
        assert codec.decode_value(codec.encode_value(value)) == value


def test_object_order_and_typed_strings(codec):
    value = {'z': 'SELF', 'scores': [1], 'mode': Atom('MODE_HANCHAN'), 'a': b''}
    expected = ids(codec, 'OBJ F_MODE MODE_HANCHAN F_SCORES LIST U1 END_LIST UTF8 BYTE_61 END_UTF8 BYTES END_BYTES UTF8 BYTE_7A END_UTF8 UTF8 BYTE_53 BYTE_45 BYTE_4C BYTE_46 END_UTF8 END_OBJ')
    assert codec.encode_value(value) == expected
    assert codec.decode_value(expected) == value
    assert codec.encode_value(dict(reversed(list(value.items())))) == expected


